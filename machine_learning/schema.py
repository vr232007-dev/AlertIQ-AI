"""
Shared Alert Schema for AlertIQ AI.

This module defines the canonical data schema and validation models for security
alerts ingested by AlertIQ AI. It provides Pydantic data validation contracts,
allowed categorical values, feature lists, and validation utility functions.
"""

from typing import Optional, List, Dict, Any, Literal
from datetime import datetime, timezone
from pydantic import BaseModel, Field, field_validator
import pandas as pd


# ==============================================================================
# Allowed Vocabulary & Enums for Categorical Features
# ==============================================================================
ALLOWED_ALERT_TYPES: List[str] = [
    "Brute_Force",
    "Malware_Detection",
    "Data_Exfiltration",
    "Privilege_Escalation",
    "DDoS_Attempt",
    "Phishing_Campaign",
    "Port_Scanning",
    "SQL_Injection",
    "Anomalous_Login",
    "Unauthorized_Access"
]

ALLOWED_PROTOCOLS: List[str] = [
    "TCP",
    "UDP",
    "ICMP",
    "HTTP",
    "HTTPS",
    "DNS"
]

ALLOWED_NETWORK_ZONES: List[str] = [
    "Internal",
    "DMZ",
    "External",
    "Cloud_VPC",
    "PCI_DSS"
]

ALLOWED_ASSET_CRITICALITIES: List[str] = [
    "Low",
    "Medium",
    "High",
    "Critical"
]

ALLOWED_USER_ROLES: List[str] = [
    "Standard_User",
    "Domain_Admin",
    "Service_Account",
    "Contractor",
    "System"
]

ALLOWED_RAW_SEVERITIES: List[str] = [
    "Informational",
    "Low",
    "Medium",
    "High"
]

ALLOWED_MITRE_TACTICS: List[str] = [
    "Initial_Access",
    "Execution",
    "Persistence",
    "Privilege_Escalation",
    "Defense_Evasion",
    "Credential_Access",
    "Discovery",
    "Lateral_Movement",
    "Exfiltration",
    "Impact"
]

ALLOWED_PRIORITIES: List[str] = [
    "Low",
    "Medium",
    "High",
    "Critical"
]


# ==============================================================================
# Feature Definitions for Preprocessing and Modeling
# ==============================================================================
NUMERIC_FEATURES: List[str] = [
    "event_count",
    "bytes_transferred",
    "failed_login_attempts",
    "source_port",
    "destination_port",
    "is_known_malicious_ip",
    "is_off_hours"
]

CATEGORICAL_FEATURES: List[str] = [
    "alert_type",
    "protocol",
    "network_zone",
    "asset_criticality",
    "user_role",
    "raw_severity",
    "mitre_tactic"
]

FEATURE_COLUMNS: List[str] = NUMERIC_FEATURES + CATEGORICAL_FEATURES
METADATA_COLUMNS: List[str] = ["alert_id", "timestamp", "source_ip", "destination_ip"]
TARGET_COLUMN: str = "priority"
ALL_COLUMNS: List[str] = METADATA_COLUMNS + FEATURE_COLUMNS + [TARGET_COLUMN]


# ==============================================================================
# Pydantic Schemas for Strong Typing & API Contracts
# ==============================================================================
class SecurityAlert(BaseModel):
    """
    Standard Security Alert data contract conforming to AlertIQ AI shared schema.
    Used for alert ingestion, pipeline validation, and real-time inference.
    """
    alert_id: str = Field(
        ...,
        description="Unique identifier for the security alert, e.g. 'ALT-2026-0001'"
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when the alert was generated by sensor/SIEM"
    )
    alert_type: str = Field(
        ...,
        description="Class of detection/attack pattern observed"
    )
    source_ip: str = Field(
        ...,
        description="Source IP address initiating the connection or traffic"
    )
    destination_ip: str = Field(
        ...,
        description="Target asset destination IP address"
    )
    source_port: int = Field(
        ...,
        ge=0,
        le=65535,
        description="Originating network port number (0-65535)"
    )
    destination_port: int = Field(
        ...,
        ge=0,
        le=65535,
        description="Target service network port number (0-65535)"
    )
    protocol: str = Field(
        ...,
        description="Network protocol used (e.g. TCP, HTTPS)"
    )
    network_zone: str = Field(
        ...,
        description="Segmented network boundary of target asset (e.g. DMZ, PCI_DSS)"
    )
    asset_criticality: str = Field(
        ...,
        description="Operational value of target system (Low, Medium, High, Critical)"
    )
    user_role: str = Field(
        ...,
        description="Associated security context or account privilege level"
    )
    raw_severity: str = Field(
        ...,
        description="Original unadjusted severity level assigned by sensor/SIEM rule"
    )
    event_count: int = Field(
        ...,
        ge=1,
        description="Count of aggregated events or log lines linked to this alert"
    )
    bytes_transferred: float = Field(
        ...,
        ge=0.0,
        description="Total payload data transferred in bytes"
    )
    failed_login_attempts: int = Field(
        ...,
        ge=0,
        description="Number of failed authentication attempts observed"
    )
    mitre_tactic: str = Field(
        ...,
        description="Mapped MITRE ATT&CK enterprise tactic"
    )
    is_known_malicious_ip: int = Field(
        ...,
        ge=0,
        le=1,
        description="Threat Intelligence match indicator: 1 if flagged, 0 otherwise"
    )
    is_off_hours: int = Field(
        ...,
        ge=0,
        le=1,
        description="Temporal flag: 1 if event occurred outside business hours, 0 otherwise"
    )
    priority: Optional[str] = Field(
        default=None,
        description="Ground-truth triage priority (Low, Medium, High, Critical). None for unlabelled alerts."
    )

    @field_validator("alert_type")
    def validate_alert_type(cls, v: str) -> str:
        if v not in ALLOWED_ALERT_TYPES:
            raise ValueError(f"Invalid alert_type '{v}'. Allowed: {ALLOWED_ALERT_TYPES}")
        return v

    @field_validator("protocol")
    def validate_protocol(cls, v: str) -> str:
        if v not in ALLOWED_PROTOCOLS:
            raise ValueError(f"Invalid protocol '{v}'. Allowed: {ALLOWED_PROTOCOLS}")
        return v

    @field_validator("network_zone")
    def validate_network_zone(cls, v: str) -> str:
        if v not in ALLOWED_NETWORK_ZONES:
            raise ValueError(f"Invalid network_zone '{v}'. Allowed: {ALLOWED_NETWORK_ZONES}")
        return v

    @field_validator("asset_criticality")
    def validate_asset_criticality(cls, v: str) -> str:
        if v not in ALLOWED_ASSET_CRITICALITIES:
            raise ValueError(f"Invalid asset_criticality '{v}'. Allowed: {ALLOWED_ASSET_CRITICALITIES}")
        return v

    @field_validator("user_role")
    def validate_user_role(cls, v: str) -> str:
        if v not in ALLOWED_USER_ROLES:
            raise ValueError(f"Invalid user_role '{v}'. Allowed: {ALLOWED_USER_ROLES}")
        return v

    @field_validator("raw_severity")
    def validate_raw_severity(cls, v: str) -> str:
        if v not in ALLOWED_RAW_SEVERITIES:
            raise ValueError(f"Invalid raw_severity '{v}'. Allowed: {ALLOWED_RAW_SEVERITIES}")
        return v

    @field_validator("mitre_tactic")
    def validate_mitre_tactic(cls, v: str) -> str:
        if v not in ALLOWED_MITRE_TACTICS:
            raise ValueError(f"Invalid mitre_tactic '{v}'. Allowed: {ALLOWED_MITRE_TACTICS}")
        return v

    @field_validator("priority")
    def validate_priority(cls, v: Optional[str]) -> Optional[str]:
        if v is not None and v not in ALLOWED_PRIORITIES:
            raise ValueError(f"Invalid priority '{v}'. Allowed: {ALLOWED_PRIORITIES}")
        return v


class AlertPrioritizationResult(BaseModel):
    """
    Standard output contract for model prediction inference.
    """
    alert_id: str
    predicted_priority: str
    confidence: float
    probabilities: Dict[str, float]
    triage_recommendation: str


# ==============================================================================
# Validation Utility Functions
# ==============================================================================
def validate_alert_dict(alert_data: Dict[str, Any]) -> SecurityAlert:
    """
    Validates a single alert dictionary against the SecurityAlert schema.

    Parameters:
        alert_data (Dict[str, Any]): Raw alert dictionary.

    Returns:
        SecurityAlert: Validated Pydantic model instance.

    Raises:
        pydantic.ValidationError: If payload violates schema constraints.
    """
    return SecurityAlert(**alert_data)


def validate_alert_dataframe(df: pd.DataFrame, require_target: bool = False) -> pd.DataFrame:
    """
    Validates that a pandas DataFrame contains all required feature columns
    specified in the shared schema.

    Parameters:
        df (pd.DataFrame): Dataframe containing security alerts.
        require_target (bool): If True, also enforces existence of 'priority' column.

    Returns:
        pd.DataFrame: The validated DataFrame.

    Raises:
        ValueError: If any required feature or target column is missing.
    """
    missing_features = [col for col in FEATURE_COLUMNS if col not in df.columns]
    if missing_features:
        raise ValueError(
            f"DataFrame is missing required schema feature columns: {missing_features}"
        )

    if require_target and TARGET_COLUMN not in df.columns:
        raise ValueError(
            f"DataFrame is missing target column '{TARGET_COLUMN}' required for training."
        )

    return df
